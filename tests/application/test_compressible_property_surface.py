def _class(name):
    module = importlib.import_module(f"rocketforge.application.analysis.{CONTROLLERS[name]}")
    return getattr(module, name)


def _surface(cls) -> dict:
    meta = cls.staticMetaObject
    properties, flags = {}, {}
    for i in range(meta.propertyOffset(), meta.propertyCount()):
        p = meta.property(i)
        tail = ("const" if p.isConstant()
                else bytes(p.notifySignal().methodSignature()).decode() if p.hasNotifySignal() else "-")
        properties[p.name()] = f"{p.typeName()} {'rw' if p.isWritable() else 'r'} {tail}"
        flags[p.name()] = (p.isReadable(), p.isResettable(), p.isFinal(), p.isDesignable(),
                           p.isScriptable(), p.isStored(), p.isUser())
    methods = {bytes(m.methodSignature()).decode(): f"{KINDS[m.methodType()]} {m.typeName()}"
               for m in (meta.method(i) for i in range(meta.methodOffset(), meta.methodCount()))}
    return {"properties": properties, "methods": methods, "flags": flags,
            "super": meta.superClass().className()}


def test_the_frozen_surface_covers_all_seven_controllers():
    assert set(SURFACE) == set(CONTROLLERS)
    assert sum(len(v["properties"]) for v in SURFACE.values()) == 372
    assert sum(len(v["methods"]) for v in SURFACE.values()) == 155


@pytest.mark.parametrize("name", sorted(CONTROLLERS))
def test_every_property_keeps_its_name_type_access_and_notify_signal(name):
    live = _surface(_class(name))["properties"]
    frozen = SURFACE[name]["properties"]
    missing = sorted(set(frozen) - set(live))
    added = sorted(set(live) - set(frozen))
    changed = {k: (frozen[k], live[k]) for k in set(frozen) & set(live) if frozen[k] != live[k]}
    assert not missing and not added and not changed, (missing, added, changed)


